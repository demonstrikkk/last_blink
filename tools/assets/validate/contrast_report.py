"""Compute WCAG 2.1 contrast ratios for the Last Blink palette.

Run:  python tools/assets/validate/contrast_report.py
Outputs a markdown table to stdout and writes docs/contrast_report.md.
"""

from __future__ import annotations

from pathlib import Path

PALETTE: dict[str, str] = {
    # Night neutrals
    "ink-900": "#070A0F",
    "ink-800": "#0D131B",
    "ink-700": "#141C26",
    "ink-600": "#1E2833",
    "ink-500": "#2B3846",
    "steel-400": "#3E4E5F",
    "steel-300": "#5A6E82",
    "steel-200": "#8A9BAE",
    "steel-100": "#C3CFDB",
    # Diegetic neon
    "neon-cyan": "#38E1E8",
    "neon-magenta": "#FF5CC8",
    "neon-amber": "#FFB24D",
    "neon-green": "#6FF2A8",
    # Semantic
    "danger": "#FF4D5E",
    "warning": "#FFC24B",
    "success": "#5BE58A",
    "info": "#58C8FF",
    # Identity
    "identity-v1": "#38E1E8",
    "identity-v2": "#FF5CC8",
    "identity-echo": "#A9F0C6",
    "identity-morrow": "#E8DCC6",
    "identity-morrow-accent": "#FF7A45",
    # Text tokens
    "text-primary": "#EAF1F8",
    "text-secondary": "#A9B8C7",
    "text-muted": "#7E8FA1",
}

# Backgrounds that text and icons actually sit on.
SURFACES = ["ink-900", "ink-800", "ink-700", "ink-600"]
FOREGROUNDS = [
    "text-primary",
    "text-secondary",
    "text-muted",
    "steel-200",
    "neon-cyan",
    "neon-magenta",
    "neon-amber",
    "neon-green",
    "danger",
    "warning",
    "success",
    "info",
    "identity-echo",
    "identity-morrow",
    "identity-morrow-accent",
]


def _srgb_to_linear(channel: int) -> float:
    c = channel / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def relative_luminance(hex_colour: str) -> float:
    value = hex_colour.lstrip("#")
    r, g, b = (int(value[i : i + 2], 16) for i in (0, 2, 4))
    return (
        0.2126 * _srgb_to_linear(r)
        + 0.7152 * _srgb_to_linear(g)
        + 0.0722 * _srgb_to_linear(b)
    )


def contrast_ratio(fg: str, bg: str) -> float:
    l1 = relative_luminance(fg)
    l2 = relative_luminance(bg)
    lighter, darker = max(l1, l2), min(l1, l2)
    return (lighter + 0.05) / (darker + 0.05)


def grade(ratio: float) -> str:
    if ratio >= 7.0:
        return "AAA body"
    if ratio >= 4.5:
        return "AA body"
    if ratio >= 3.0:
        return "AA large / UI"
    return "decorative only"


def main() -> None:
    rows: list[str] = []
    header = "| Foreground | " + " | ".join(f"on {b}" for b in SURFACES) + " |"
    divider = "|---" * (len(SURFACES) + 1) + "|"
    rows += [header, divider]

    for fg_name in FOREGROUNDS:
        cells = []
        for bg_name in SURFACES:
            ratio = contrast_ratio(PALETTE[fg_name], PALETTE[bg_name])
            cells.append(f"{ratio:.2f}:1")
        rows.append(f"| `{fg_name}` | " + " | ".join(cells) + " |")

    worst_text = min(
        contrast_ratio(PALETTE["text-secondary"], PALETTE[bg]) for bg in SURFACES
    )

    body = "\n".join(
        [
            "# Palette contrast report",
            "",
            "Generated by `tools/assets/validate/contrast_report.py` using the WCAG 2.1",
            "relative-luminance formula. Values are ratios; anything below 4.5:1 must",
            "not carry body text.",
            "",
            *rows,
            "",
            f"Worst-case `text-secondary` on any dark surface: **{worst_text:.2f}:1** "
            f"({grade(worst_text)}).",
            "",
            "## Rules derived from these numbers",
            "",
            "- Body text uses `text-primary` or `text-secondary` only.",
            "- `text-muted` is restricted to decorative or disabled labels that are also",
            "  distinguishable by position and shape.",
            "- Neon colours are never the sole carrier of meaning: every state also has a",
            "  glyph, stroke pattern, or text label.",
            "- Warning/danger chips pair colour with an icon and an explicit word.",
            "",
        ]
    )

    out = Path("docs/contrast_report.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, encoding="utf-8")
    print(body)


if __name__ == "__main__":
    main()
